/* DbyPciePhySeq.h — PCIe0's PHY programming, copied verbatim from THIS tablet's device tree.
 *
 * PROVENANCE (not invented, not taken from another board)
 *   /root/dby-full.dtb, decompiled with `dtc -I dtb -O dts -o /root/dby-full.dts`, line 8983:
 *     qcom,phy-sequence = <99 triples>
 *   The triples are {register offset inside the PCIe0 PHY window, value, delay}, and this board's
 *   tree carries every delay as 0, so the table below is 99 writes and nothing else.  Offsets run
 *   0x010..0xCE0, which is inside the one page the device tree gives the PHY
 *   (`phy` = 0x01C06000 + 0x1000, /root/dby-full.dts:8931).
 *
 * WHY IT IS A SEPARATE FILE
 *   297 numbers would bury the stage logic in package/DbyPcie.cpp.  Generating the array from the
 *   device tree with a script (rather than retyping it) is the only way this file can be trusted:
 *   one transposed digit is a silent PHY misconfiguration that no host check would catch.
 *
 * HOW IT IS USED
 *   stage3a() writes each entry into the mapped PHY window in order, honouring `delay` in microseconds
 *   after the write when it is non-zero (this board has none).  M2a deliberately did not replay it: it
 *   only released the PCIe0 resets, and the link will not train without this sequence.
 */
