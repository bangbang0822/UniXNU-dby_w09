#!/usr/bin/env python3
"""Emit build/dby-touch/DbyTouchFwImages.h from this unit's own Novatek THP firmware files.

The images are vendor data taken from the stock package's libafehalW2599Z<project>.so
(proprietary-files.txt lists them, and they never enter Git), so the generated header
lives under build/ and is never committed either. The picker, the default selection and
the name matching stay in package/DbyTouch/DbyTouchFw.h -- only bytes and the table that
points at them are generated.

Each image is checked against the ILM/DLM length and CRC recorded below, which are the
values the closed HAL streams and the ones the accepted hardware boot ran with. A file
that does not match is refused rather than embedded: a silently different firmware is a
worse outcome than a touch panel that does not come up.

With no firmware present the header still emits a well-formed table whose entries carry
length 0. The uploader bounds every write by that length, so the driver stops before the
download stage and logs it, exactly as scripts/gen-touch-firmware.py documents for the
single-image path.

Usage:
  python3 scripts/gen-touch-firmware-multi.py                    # .cache/firmware/novatek
  python3 scripts/gen-touch-firmware-multi.py --firmware-dir DIR --out DIR
"""
import argparse
import os
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FW = ROOT / '.cache/firmware/novatek'
DEFAULT_OUT = ROOT / 'build/dby-touch'

LEN = 0x30000

# project, file, ILM (off, sram, len, crc), DLM (off, sram, len, crc)
PROJECTS = (
    ('W2599Z1100', 'nt36523_Z1100.bin',
     (0x00200, 0x000000, 0x146AB, 0x428647E2), (0x22000, 0x020000, 0x0BC47, 0x45718EE7)),
    ('W2599Z1300', 'nt36523_Z1300.bin',
     (0x00200, 0x000000, 0x147B7, 0xC9DDC415), (0x22000, 0x020000, 0x0BC47, 0x48FA918D)),
    ('W2599Z2700', 'nt36523_Z2700.bin',
     (0x00200, 0x000000, 0x14547, 0x18F0D943), (0x22000, 0x020000, 0x0BC47, 0xB674D6DB)),
)


def crc_mpeg2(data):
    """CRC-32/MPEG-2: poly 0x04C11DB7, init 0xFFFFFFFF, no reflection, no final xor."""
    crc = 0xFFFFFFFF
    for byte in data:
        crc ^= byte << 24
        for _ in range(8):
            crc = ((crc << 1) ^ 0x04C11DB7) & 0xFFFFFFFF if crc & 0x80000000 else (crc << 1) & 0xFFFFFFFF
    return crc


def check(path, part):
    off, _sram, length, want = part
    blob = path.read_bytes()[off:off + length + 1]
    if len(blob) != length + 1:
        raise SystemExit(f'{path.name}: short read for partition at {off:#x} '
                         f'({len(blob)} bytes, expected {length + 1})')
    got = crc_mpeg2(blob)
    if got != want:
        raise SystemExit(f'{path.name}: CRC {got:#010x} at offset {off:#x} does not match '
                         f'the recorded {want:#010x}; refusing to embed unknown firmware')


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--firmware-dir', type=Path, default=DEFAULT_FW)
    parser.add_argument('--out', type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    out_dir = args.out if args.out.is_absolute() else (Path.cwd() / args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    available = []
    missing = []
    for project, name, ilm, dlm in PROJECTS:
        path = args.firmware_dir / name
        if path.is_file():
            check(path, ilm)
            check(path, dlm)
            available.append((project, name, path, ilm, dlm))
        else:
            missing.append((project, name, ilm, dlm))

    lines = [
        '/* Generated by scripts/gen-touch-firmware-multi.py. Do not edit, do not commit.',
        ' *',
        ' * The arrays below are vendor firmware taken from this unit\'s stock package;',
        ' * proprietary-files.txt lists the sources and they live in .cache/firmware only.',
        ' */',
        '#ifndef DBY_TOUCH_FW_IMAGES_H',
        '#define DBY_TOUCH_FW_IMAGES_H',
        '',
    ]

    if available:
        lines.append(f'#define DBY_TOUCH_FW_IMAGES_PRESENT {len(available)}')
        lines.append('')
        for project, name, path, _ilm, _dlm in available:
            data = path.read_bytes()
            if len(data) != LEN:
                raise SystemExit(f'{name}: {len(data)} bytes, expected {LEN:#x} (0x30000)')
            lines.append(f'static const unsigned char dbyTouchFwImage{project[6:]}[DBY_TOUCH_FW_LEN] = {{')
            for i in range(0, len(data), 16):
                chunk = ', '.join(f'0x{b:02x}' for b in data[i:i + 16])
                lines.append('\t' + chunk + ',')
            lines.append('};')
            lines.append('')
    else:
        lines.append('#define DBY_TOUCH_FW_IMAGES_PRESENT 0')

    # The table is always well formed; a missing image contributes length 0, which the
    # uploader's bounds check turns into a refusal instead of a write.
    lines.append('static const struct dbyTouchFwSel gDbyTouchFwAll[] = {')
    present = {project for project, *_ in available}
    for project, name, ilm, dlm in PROJECTS:
        image = f'dbyTouchFwImage{project[6:]}' if project in present else 'nullptr'
        length = 'DBY_TOUCH_FW_LEN' if project in present else '0'
        lines.append(f'\t{{ "{project}", "{name}", {length}, {image},')
        lines.append(f'\t  {ilm[0]:#07x}U, {ilm[1]:#07x}U, {ilm[2]:#07x}U, {ilm[3]:#010x}U,')
        lines.append(f'\t  {dlm[0]:#07x}U, {dlm[1]:#07x}U, {dlm[2]:#07x}U, {dlm[3]:#010x}U }},')
    lines.append('};')
    lines.append('')
    lines.append('#endif /* DBY_TOUCH_FW_IMAGES_H */')

    target = out_dir / 'DbyTouchFwImages.h'
    target.write_text('\n'.join(lines) + '\n')

    print(f'{target}: {len(available)} image(s) embedded')
    for project, name, _path, _ilm, _dlm in available:
        print(f'  {project} <- {name}')
    for project, name, _ilm, _dlm in missing:
        print(f'  {project}: no {name} in {args.firmware_dir}', file=sys.stderr)
    if missing:
        print('  note: the touch upload will not run without these; see proprietary-files.txt',
              file=sys.stderr)


if __name__ == '__main__':
    main()
